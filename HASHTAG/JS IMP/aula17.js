// #EXPONENCIAÇÃO

let base = 2;
let expoente = 3;
let resultado = base ** expoente; // 2 elevado a 3
console.log(resultado);

// #PÓS INCREMENTO

let controle = 0;
console.log(controle++); // aumenta 1 sempre que eu executo o programa, apenas um comando
console.log(controle); // imprime o valor atual do controle, que é 1
console.log(controle++); // aumenta 1 sempre que eu executo o programa, apenas um comando
console.log(controle); // imprime o valor atual do controle, que é 2

// #PÓS DECREMENTO

let control = 0;
console.log(control--); // diminui 1 sempre que eu executo o programa, apenas um comando
console.log(control); // imprime o valor atual do controle, que é 0
console.log(control--); // diminui 1 sempre que eu executo o programa, apenas um comando
console.log(control); // imprime o valor atual do controle, que é -1

// #PRÉ INCREMENTO

let controle1 = 0;
console.log(++controle1);
console.log(++controle1);

// #PRÉ DECREMENTO

let controle2 = 0;
console.log(--controle2);
console.log(--controle2);
